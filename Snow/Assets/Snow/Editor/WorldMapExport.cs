    /// <summary>
    /// Tools / Snow / World Sync / Export Whole Map: the open location as a light map set for Blender
    /// (docs/gdd/WORLD_SYNC_CONTRACT.md), source/world_sync/forest/map/ —
    ///  - ground.r16 (uint16 heights of all Terrain tiles, stitched without resampling, rows south → north) + holes.u8
    ///    (1 = ground, 0 = hole) + paint.png (the layers mixed as on the Terrain, <see cref="PaintPxPerM"/> px per m);
    ///  - meshes.bin: every LOD0 mesh once (Blender axes, winding for Blender), materials with their base textures in
    ///    textures/;
    ///  - map.json: placed objects (root + its mesh instances, the WorldId sync id on the root), Terrain trees as
    ///    trees.bin (prototype, Unity x y z, yaw, width, height per tree) with their prototypes' parts, lamps.
    /// tools/blender_context/build_map.py makes map.blend from it (run here when Blender is set in areas.json). Read-only
    /// for the project. Axes as in every package contract: Blender (x, y, z) = Unity (-x, -z, y).
    /// </summary>
    public static class WorldMapExport
    {
        const string OutDir = "../source/world_sync/forest/map";
        const string AreasFile = "../tools/blender_context/areas.json";
        const float PaintPxPerM = 1f, MaxObjectSize = 300f;
        static readonly CultureInfo Ci = CultureInfo.InvariantCulture;

        [Serializable] class Ground { public string file, holes; public int nx, nz; public float x0, z0, step, hmin, hmax; }
        [Serializable] class Paint { public string file; public float pxPerM; }
        [Serializable] class Mat { public string name, texture; public float[] color; public bool cutout; }
        [Serializable] class MeshRec { public string id, name, fbx; public int v, offset; public bool uv; public int[] subs; public string[] materials; }
        [Serializable] class Meshes { public string file; public MeshRec[] list; }
        [Serializable] class Root { public string key, worldId, name, path, group, prefab; public float[] matrix; }
        [Serializable] class Inst { public string root, mesh, name; public float[] matrix; }
        [Serializable] class Part { public string mesh; public float[] matrix; }
        [Serializable] class Proto { public string name, prefab; public Part[] parts; }
        [Serializable] class Trees { public string file, layout; public int count; public Proto[] prototypes; }
        [Serializable] class Lamp { public string name, path, type; public bool enabled; public float[] color, matrix; public float intensity, range, spotAngle; }
        [Serializable]
        class MapFile
        {
            public int version = 1;
            public string location, scene, exported, axes, note;
            public float[] box;
            public Ground ground;
            public Paint paint;
            public Mat[] materials;
            public Meshes meshes;
            public Root[] roots;
            public Inst[] instances;
            public Trees trees;
            public Lamp[] lights;
            public string[] skipped;
        }
        [Serializable] class AreasDef { public string blender; }

        [MenuItem("Tools/Snow/World Sync/Export Whole Map")]
