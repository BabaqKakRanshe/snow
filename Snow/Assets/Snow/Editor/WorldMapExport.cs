        public static string Export(bool buildBlend)
        {
            Terrain[] ts = Terrain.activeTerrains.Where(t => t != null && t.terrainData != null).ToArray();
            if (ts.Length == 0) return "[Snow] Whole map: no Terrain in the open scene.";
            var sw = Stopwatch.StartNew();
            string dir = Full(OutDir);
            if (Directory.Exists(dir)) Directory.Delete(dir, true);
            Directory.CreateDirectory(Path.Combine(dir, "textures"));
            var scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
            var map = new MapFile
            {
                location = scene.name, scene = scene.path, exported = DateTime.Now.ToString("yyyy-MM-dd HH:mm", Ci),
                axes = "Blender (x, y, z) = Unity (-x, -z, y); matrices are Blender world matrices, row-major 4x4; ground, box and trees.bin in Unity metres",
                note = "Generated by Unity Tools / Snow / World Sync / Export Whole Map. Do not edit: export again instead.",
            };
            var skipped = new List<string>();
            try
            {
                EditorUtility.DisplayProgressBar("Whole map", "Ground", 0.05f);
                map.ground = WriteGround(ts, dir, out Vector4 box);
                map.box = new[] { box.x, box.y, box.z, box.w };
                EditorUtility.DisplayProgressBar("Whole map", "Paint", 0.25f);
                map.paint = new Paint { file = WritePaint(ts, box, dir), pxPerM = PaintPxPerM };

                EditorUtility.DisplayProgressBar("Whole map", "Objects", 0.5f);
                var meshes = new MeshTable(dir);
                var roots = new Dictionary<Transform, Root>();
                var inst = new List<Inst>();
                foreach (GameObject top in scene.GetRootGameObjects())
                    foreach (Renderer r in top.GetComponentsInChildren<Renderer>(false))
                    {
                        if (!(r is MeshRenderer || r is SkinnedMeshRenderer) || !r.enabled || r.name.StartsWith("__", StringComparison.Ordinal)) continue;
                        if (r.bounds.size.x > MaxObjectSize || r.bounds.size.z > MaxObjectSize) { skipped.Add(BlenderContextExport.PathOf(r.transform) + " (spans the map)"); continue; }
                        if (!BlenderContextExport.Lod0(r)) continue;
                        Mesh mesh = r is SkinnedMeshRenderer smr ? smr.sharedMesh : r.GetComponent<MeshFilter>()?.sharedMesh;
                        if (mesh == null) continue;
                        string id = meshes.Of(mesh, r.sharedMaterials);
                        Transform rootT = BlenderContextExport.RootOf(r.transform);
                        if (!roots.TryGetValue(rootT, out Root root))
                            roots[rootT] = root = new Root
                            {
                                key = $"r{roots.Count:00000}", name = rootT.name, path = BlenderContextExport.PathOf(rootT), group = BlenderContextExport.GroupOf(rootT),
                                prefab = PrefabUtility.GetPrefabAssetPathOfNearestInstanceRoot(rootT.gameObject) ?? "",
                                worldId = rootT.TryGetComponent(out WorldId w) ? w.id : "", matrix = BlenderContextExport.Blender(rootT.localToWorldMatrix),
                            };
                        inst.Add(new Inst { root = root.key, mesh = id, name = r.name, matrix = BlenderContextExport.Blender(r.localToWorldMatrix) });
                    }
                map.roots = roots.Values.ToArray();
                map.instances = inst.ToArray();

                EditorUtility.DisplayProgressBar("Whole map", "Terrain trees", 0.7f);
                map.trees = WriteTrees(ts, dir, meshes);
                map.lights = Lamps(scene).ToArray();
                map.meshes = new Meshes { file = "meshes.bin", list = meshes.Close() };
                map.materials = meshes.Materials();
            }
            finally { EditorUtility.ClearProgressBar(); }
            map.skipped = skipped.ToArray();
            File.WriteAllText(Path.Combine(dir, "map.json"), JsonUtility.ToJson(map, false));
            foreach (string py in new[] { "build_map.py", "export_moves.py" })
                File.Copy(Full("../tools/blender_context/" + py), Path.Combine(dir, py), true);
            File.WriteAllText(Path.Combine(dir, "README.md"), Readme(map), new UTF8Encoding(false));

            string blend = "not built";
            if (buildBlend)
            {
                EditorUtility.DisplayProgressBar("Whole map", "Blender: map.blend", 0.85f);
                try { blend = BuildBlend(dir); }
                finally { EditorUtility.ClearProgressBar(); }
            }
            long bytes = new DirectoryInfo(dir).GetFiles("*", SearchOption.AllDirectories).Where(f => !f.Name.EndsWith(".blend", StringComparison.Ordinal)).Sum(f => f.Length);
            return $"[Snow] Whole map -> {dir}: ground {map.ground.nx} x {map.ground.nz} ({map.ground.step:0.###} m), {map.roots.Length} objects, " +
                   $"{map.instances.Length} mesh instances of {map.meshes.list.Length} meshes, {map.materials.Length} materials, {map.trees.count} Terrain trees " +
                   $"({map.trees.prototypes.Length} models), {map.lights.Length} lamps, {skipped.Count} skipped; set {bytes / 1048576f:0.0} MB; map.blend: {blend}; {sw.Elapsed.TotalSeconds:0} s.";
        }

