        /// <summary>All tiles on one grid: the tiles share their edge samples, so tile (i, j) starts at sample
        /// (i, j) * (res - 1). Heights in world metres, stored as uint16 between the lowest and highest sample.</summary>
        static Ground WriteGround(Terrain[] ts, string dir, out Vector4 box)
        {
            TerrainData td0 = ts[0].terrainData;
            int res = td0.heightmapResolution;
            float step = td0.size.x / (res - 1);
            float x0 = ts.Min(t => t.transform.position.x), z0 = ts.Min(t => t.transform.position.z);
            float x1 = ts.Max(t => t.transform.position.x + t.terrainData.size.x), z1 = ts.Max(t => t.transform.position.z + t.terrainData.size.z);
            box = new Vector4(x0, z0, x1, z1);
            int nx = Mathf.RoundToInt((x1 - x0) / step) + 1, nz = Mathf.RoundToInt((z1 - z0) / step) + 1;
            var h = new float[nz, nx];
            var solid = new byte[(nz - 1) * (nx - 1)];
            for (int i = 0; i < solid.Length; i++) solid[i] = 1;
            float hmin = float.MaxValue, hmax = float.MinValue;
            foreach (Terrain t in ts)
            {
                TerrainData td = t.terrainData;
                if (td.heightmapResolution != res) Debug.LogWarning($"[Snow] Whole map: {td.name} has heightmap {td.heightmapResolution}, not {res}; its heights are sampled.");
                Vector3 o = t.transform.position;
                int ox = Mathf.RoundToInt((o.x - x0) / step), oz = Mathf.RoundToInt((o.z - z0) / step);
                int r = td.heightmapResolution;
                float[,] hs = td.GetHeights(0, 0, r, r);
                for (int z = 0; z < r; z++)
                    for (int x = 0; x < r; x++)
                    {
                        int gx = ox + Mathf.RoundToInt(x * (td.size.x / (r - 1)) / step), gz = oz + Mathf.RoundToInt(z * (td.size.z / (r - 1)) / step);
                        if (gx < 0 || gz < 0 || gx >= nx || gz >= nz) continue;
                        float y = o.y + hs[z, x] * td.size.y;
                        h[gz, gx] = y;
                        if (y < hmin) hmin = y;
                        if (y > hmax) hmax = y;
                    }
                bool[,] holes = td.GetHoles(0, 0, r - 1, r - 1);
                for (int z = 0; z < r - 1; z++)
                    for (int x = 0; x < r - 1; x++)
                    {
                        if (holes[z, x]) continue;                                   // true = ground
                        int gx = ox + x, gz = oz + z;
                        if (gx < nx - 1 && gz < nz - 1) solid[gz * (nx - 1) + gx] = 0;
                    }
            }
            var raw = new byte[nx * nz * 2];
            float span = Mathf.Max(hmax - hmin, 0.001f);
            for (int z = 0; z < nz; z++)
                for (int x = 0; x < nx; x++)
                {
                    int v = Mathf.Clamp(Mathf.RoundToInt((h[z, x] - hmin) / span * 65535f), 0, 65535);
                    int k = (z * nx + x) * 2;
                    raw[k] = (byte)(v & 0xff);
                    raw[k + 1] = (byte)(v >> 8);
                }
            File.WriteAllBytes(Path.Combine(dir, "ground.r16"), raw);
            File.WriteAllBytes(Path.Combine(dir, "holes.u8"), solid);
            return new Ground { file = "ground.r16", holes = "holes.u8", nx = nx, nz = nz, x0 = x0, z0 = z0, step = step, hmin = hmin, hmax = hmax };
        }

        /// <summary>The paint as one picture, tile by tile (one tile's alphamaps in memory at a time).</summary>
        static string WritePaint(Terrain[] ts, Vector4 box, string dir)
        {
            int w = Mathf.CeilToInt((box.z - box.x) * PaintPxPerM), h = Mathf.CeilToInt((box.w - box.y) * PaintPxPerM);
            var px = new Color32[w * h];
            var layerTex = new Dictionary<TerrainLayer, Texture2D>();
            Texture2D Readable(TerrainLayer l)
            {
                if (layerTex.TryGetValue(l, out Texture2D t)) return t;
                string p = l.diffuseTexture != null ? AssetDatabase.GetAssetPath(l.diffuseTexture) : null;
                t = null;
                if (!string.IsNullOrEmpty(p) && File.Exists(p))
                {
                    t = new Texture2D(2, 2) { wrapMode = TextureWrapMode.Repeat, filterMode = FilterMode.Point };
                    if (!t.LoadImage(File.ReadAllBytes(p))) t = null;
                }
                return layerTex[l] = t;
            }
            foreach (Terrain t in ts)
            {
                TerrainData td = t.terrainData;
                Vector3 o = t.transform.position;
                float[,,] map = td.GetAlphamaps(0, 0, td.alphamapWidth, td.alphamapHeight);
                TerrainLayer[] layers = td.terrainLayers;
                int px0 = Mathf.Max(0, Mathf.FloorToInt((o.x - box.x) * PaintPxPerM)), px1 = Mathf.Min(w, Mathf.CeilToInt((o.x + td.size.x - box.x) * PaintPxPerM));
                int py0 = Mathf.Max(0, Mathf.FloorToInt((o.z - box.y) * PaintPxPerM)), py1 = Mathf.Min(h, Mathf.CeilToInt((o.z + td.size.z - box.y) * PaintPxPerM));
                for (int y = py0; y < py1; y++)
                    for (int x = px0; x < px1; x++)
                    {
                        float wx = box.x + (x + 0.5f) / PaintPxPerM, wz = box.y + (y + 0.5f) / PaintPxPerM;
                        if (wx < o.x || wz < o.z || wx > o.x + td.size.x || wz > o.z + td.size.z) continue;
                        int ax = Mathf.Clamp((int)((wx - o.x) / td.size.x * td.alphamapWidth), 0, td.alphamapWidth - 1);
                        int az = Mathf.Clamp((int)((wz - o.z) / td.size.z * td.alphamapHeight), 0, td.alphamapHeight - 1);
                        Color c = Color.black;
                        for (int l = 0; l < layers.Length; l++)
                        {
                            float a = map[az, ax, l];
                            if (a <= 0.001f || layers[l] == null) continue;
                            Texture2D lt = Readable(layers[l]);
                            Vector2 tile = layers[l].tileSize;
                            Color s = lt != null ? lt.GetPixelBilinear((wx - o.x + layers[l].tileOffset.x) / tile.x, (wz - o.z + layers[l].tileOffset.y) / tile.y) : Color.gray;
                            c += s * a;
                        }
                        c.a = 1f;
                        px[y * w + x] = c;
                    }
            }
            var img = new Texture2D(w, h, TextureFormat.RGB24, false);
            img.SetPixels32(px);
            img.Apply();
            File.WriteAllBytes(Path.Combine(dir, "paint.png"), img.EncodeToPNG());
            UnityEngine.Object.DestroyImmediate(img);
            foreach (Texture2D t in layerTex.Values) if (t != null) UnityEngine.Object.DestroyImmediate(t);
            return "paint.png";
        }

