        /// <summary>meshes.bin: per mesh float32 positions (Blender axes), float32 uv when every vertex has one, then per
        /// submesh uint32 triangle indices with the winding reversed (the axis change mirrors).</summary>
        class MeshTable
        {
            readonly string _dir;
            readonly BinaryWriter _bin;
            readonly Dictionary<Mesh, MeshRec> _meshes = new Dictionary<Mesh, MeshRec>();
            readonly Dictionary<string, Mat> _mats = new Dictionary<string, Mat>(StringComparer.Ordinal);
            readonly Dictionary<string, string> _textures = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

            public MeshTable(string dir)
            {
                _dir = dir;
                _bin = new BinaryWriter(File.Create(Path.Combine(dir, "meshes.bin")));
            }

            public string Of(Mesh mesh, Material[] mats)
            {
                if (_meshes.TryGetValue(mesh, out MeshRec known)) return known.id;
                string id = $"{_meshes.Count:00000}_{BlenderContextExport.Safe(mesh.name)}";
                if (id.Length > 60) id = id.Substring(0, 60);
                Vector3[] v = mesh.vertices;
                Vector2[] uv = mesh.uv;
                bool hasUv = uv != null && uv.Length == v.Length;
                var rec = new MeshRec { id = id, name = mesh.name, fbx = AssetDatabase.GetAssetPath(mesh), v = v.Length, offset = (int)_bin.BaseStream.Position, uv = hasUv };
                foreach (Vector3 p in v) { _bin.Write(-p.x); _bin.Write(-p.z); _bin.Write(p.y); }
                if (hasUv) foreach (Vector2 t in uv) { _bin.Write(t.x); _bin.Write(t.y); }
                rec.subs = new int[mesh.subMeshCount];
                rec.materials = new string[mesh.subMeshCount];
                for (int s = 0; s < mesh.subMeshCount; s++)
                {
                    int[] tri = mesh.GetTriangles(s);
                    rec.subs[s] = tri.Length / 3;
                    for (int k = 0; k + 2 < tri.Length; k += 3) { _bin.Write((uint)tri[k + 2]); _bin.Write((uint)tri[k + 1]); _bin.Write((uint)tri[k]); }
                    rec.materials[s] = MaterialOf(mats != null && s < mats.Length ? mats[s] : null);
                }
                _meshes[mesh] = rec;
                return id;
            }

            string MaterialOf(Material m)
            {
                string name = m != null ? BlenderContextExport.Safe(m.name) : "none";
                if (_mats.ContainsKey(name)) return name;
                Color c = Color.white;
                Texture tex = null;
                bool cutout = false;
                if (m != null)
                {
                    if (m.HasProperty("_BaseColor")) c = m.GetColor("_BaseColor"); else if (m.HasProperty("_Color")) c = m.GetColor("_Color");
                    if (m.HasProperty("_BaseMap")) tex = m.GetTexture("_BaseMap");
                    if (tex == null && m.HasProperty("_MainTex")) tex = m.GetTexture("_MainTex");
                    cutout = m.IsKeywordEnabled("_ALPHATEST_ON") || (m.HasProperty("_AlphaClip") && m.GetFloat("_AlphaClip") > 0.5f);
                }
                _mats[name] = new Mat { name = name, color = new[] { c.r, c.g, c.b, c.a }, texture = Texture(tex), cutout = cutout };
                return name;
            }

            /// <summary>The texture file copied once into textures/ (pictures inside an FBX stay out).</summary>
            string Texture(Texture tex)
            {
                string p = tex != null ? AssetDatabase.GetAssetPath(tex) : null;
                if (string.IsNullOrEmpty(p) || p.EndsWith(".fbx", StringComparison.OrdinalIgnoreCase) || !File.Exists(p)) return "";
                if (_textures.TryGetValue(p, out string known)) return known;
                string name = "textures/" + Path.GetFileName(p);
                if (_textures.ContainsValue(name)) name = $"textures/{_textures.Count:0000}_{Path.GetFileName(p)}";
                File.Copy(p, Path.Combine(_dir, name), true);
                return _textures[p] = name;
            }

            public MeshRec[] Close()
            {
                _bin.Flush();
                _bin.Close();
                return _meshes.Values.ToArray();
            }

            public Mat[] Materials() => _mats.Values.ToArray();
        }

