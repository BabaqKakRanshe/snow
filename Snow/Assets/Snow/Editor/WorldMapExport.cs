        static string BuildBlend(string dir)
        {
            string exe = Environment.GetEnvironmentVariable("SNOW_BLENDER");
            if (string.IsNullOrEmpty(exe) && File.Exists(Full(AreasFile))) exe = JsonUtility.FromJson<AreasDef>(File.ReadAllText(Full(AreasFile)))?.blender;
            if (string.IsNullOrEmpty(exe) || !File.Exists(exe)) return $"Blender not found ({exe}); set 'blender' in areas.json or SNOW_BLENDER";
            string log = Path.Combine(dir, "blender_build.log");
            var psi = new ProcessStartInfo(exe, $"-b --factory-startup --python \"{Path.Combine(dir, "build_map.py")}\" -- \"{Path.Combine(dir, "map.json")}\" \"{Path.Combine(dir, "map.blend")}\"")
            {
                UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true,
            };
            var output = new StringBuilder();
            using (var p = new Process { StartInfo = psi })
            {
                p.OutputDataReceived += (_, e) => { if (e.Data != null) lock (output) output.AppendLine(e.Data); };
                p.ErrorDataReceived += (_, e) => { if (e.Data != null) lock (output) output.AppendLine(e.Data); };
                p.Start();
                p.BeginOutputReadLine();
                p.BeginErrorReadLine();
                bool done = p.WaitForExit(1_800_000);
                if (done) p.WaitForExit();
                else p.Kill();
                lock (output) File.WriteAllText(log, output.ToString());
                if (!done) return "Blender timed out (see blender_build.log)";
            }
            return File.Exists(Path.Combine(dir, "map.blend")) ? "map.blend" : "FAILED (see blender_build.log)";
        }

        static string Readme(MapFile m)
        {
            var sb = new StringBuilder();
            sb.Append($"# Карта {m.location} целиком — набор для Blender\n\n");
            sb.Append($"Выгружено из Unity {m.exported}, сцена `{m.scene}`. Правила обмена — `docs/gdd/WORLD_SYNC_CONTRACT.md`.\n\n");
            sb.Append("## Собрать сцену\n");
            sb.Append("`blender -b --factory-startup --python build_map.py -- map.json map.blend` (из этой папки). ");
            sb.Append("Земля по умолчанию через точку (`--ground-step 2`, 1,2 м); `--ground-step 1` — полная, `--no-trees` — без деревьев.\n\n");
            sb.Append("## Что внутри\n");
            sb.Append($"- `ground.r16` — высоты {m.ground.nx} × {m.ground.nz} точек через {m.ground.step.ToString("0.###", Ci)} м, uint16, строки с юга на север, ");
            sb.Append($"x с запада на восток; высота = {m.ground.hmin.ToString("0.##", Ci)} + v / 65535 × {(m.ground.hmax - m.ground.hmin).ToString("0.##", Ci)} м. ");
            sb.Append("`holes.u8` — 1 = земля, 0 = дыра (клетки между точками).\n");
