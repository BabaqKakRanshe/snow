        static Trees WriteTrees(Terrain[] ts, string dir, MeshTable meshes)
        {
            var protos = new List<Proto>();
            var byPrefab = new Dictionary<GameObject, int>();
            int count = 0;
            using (var bin = new BinaryWriter(File.Create(Path.Combine(dir, "trees.bin"))))
                foreach (Terrain t in ts)
                {
                    TerrainData td = t.terrainData;
                    Vector3 o = t.transform.position, s = td.size;
                    TreePrototype[] tp = td.treePrototypes;
                    var local = new int[tp.Length];
                    for (int i = 0; i < tp.Length; i++)
                    {
                        GameObject pf = tp[i].prefab;
                        if (pf == null) { local[i] = -1; continue; }
                        if (!byPrefab.TryGetValue(pf, out int k))
                        {
                            var parts = new List<Part>();
                            foreach (MeshRenderer r in pf.GetComponentsInChildren<MeshRenderer>(true))
                            {
                                if (!BlenderContextExport.Lod0(r)) continue;
                                Mesh m = r.GetComponent<MeshFilter>()?.sharedMesh;
                                if (m == null) continue;
                                parts.Add(new Part { mesh = meshes.Of(m, r.sharedMaterials), matrix = BlenderContextExport.Blender(pf.transform.worldToLocalMatrix * r.transform.localToWorldMatrix) });
                            }
                            byPrefab[pf] = k = protos.Count;
                            protos.Add(new Proto { name = BlenderContextExport.Safe(pf.name), prefab = AssetDatabase.GetAssetPath(pf), parts = parts.ToArray() });
                        }
                        local[i] = k;
                    }
                    foreach (TreeInstance ti in td.treeInstances)
                    {
                        int k = ti.prototypeIndex < local.Length ? local[ti.prototypeIndex] : -1;
                        if (k < 0) continue;
                        Vector3 w = o + Vector3.Scale(ti.position, s);
                        bin.Write((float)k); bin.Write(w.x); bin.Write(w.y); bin.Write(w.z);
                        bin.Write(ti.rotation); bin.Write(ti.widthScale); bin.Write(ti.heightScale);
                        count++;
                    }
                }
            return new Trees
            {
                file = "trees.bin", count = count, prototypes = protos.ToArray(),
                layout = "float32 x 7 per tree: prototype index, Unity x, y, z, yaw about +y (rad), width scale, height scale",
            };
        }

        static IEnumerable<Lamp> Lamps(UnityEngine.SceneManagement.Scene scene)
        {
            foreach (GameObject top in scene.GetRootGameObjects())
                foreach (Light l in top.GetComponentsInChildren<Light>(true))
                {
                    if (l.type == LightType.Directional) continue;
                    yield return new Lamp
                    {
                        name = l.name, path = BlenderContextExport.PathOf(l.transform), type = l.type.ToString(),
                        enabled = l.enabled && l.gameObject.activeInHierarchy, color = new[] { l.color.r, l.color.g, l.color.b },
                        intensity = l.intensity, range = l.range, spotAngle = l.spotAngle, matrix = BlenderContextExport.Blender(l.transform.localToWorldMatrix),
                    };
                }
        }

