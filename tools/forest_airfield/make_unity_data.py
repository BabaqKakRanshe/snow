"""forest_airfield 1.0 contract -> Snow/Assets/Locations/Forest/Airfield/Airfield_Unity.json for StartPropsBuilder (Unity, menu
Build Airfield Props), and the pack's textures into Airfield/Textures. As tools/forest_hut_yard/make_unity_data.py: everything in
the Unity frame of each root; nothing opens (no doors); the lights stay off in the prefab (the airfield's power lights them).

python tools/forest_airfield/make_unity_data.py
"""
import json, os, shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PKG = os.path.join(ROOT, 'source', 'assets', 'forest_airfield')
DST = os.path.join(ROOT, 'Snow', 'Assets', 'Locations', 'Forest', 'Airfield')
OUT = os.path.join(DST, 'Airfield_Unity.json')
NAMES = ['RWY_Slab', 'RWY_SlabWorn', 'RWY_Threshold', 'RWY_Num17', 'RWY_Num35', 'AF_EdgeLight', 'AF_ThresholdLight',
         'AF_EdgeMarker', 'AF_Sign', 'AF_HangarPlug']
TEXTURES = ['T_AF_Runway_BaseColor.png', 'T_AF_AFProps_BaseColor.png', 'T_AF_AFPlug_BaseColor.png', 'T_AF_Panel_BaseColor.png',
            'T_AF_Panel_Emission.png']

c = json.load(open(os.path.join(PKG, 'af_contract.json'), encoding='utf-8'))
lights = json.load(open(os.path.join(PKG, 'af_lights.json'), encoding='utf-8'))['lights']
items = []
for n in NAMES:
    it = {'name': n, 'fbx': f'Assets/Locations/Forest/Airfield/Models/{n}.fbx', 'colliders': [], 'lights': [], 'sockets': [], 'doors': []}
    for col in c['colliders']:
        if col['root'] == n:
            it['colliders'].append({'name': col['name'], 'parent': col['parent'], 'center': col['centerUnity'], 'size': col['sizeUnity']})
    for sn, s in c['sockets'].items():
        if s['root'] == n and s['kind'] != 'light':
            it['sockets'].append({'name': sn, 'kind': s['kind'], 'pos': s['posUnity']})
    for l in lights:
        if l['root'] == n:
            it['lights'].append({'name': l['socket'], 'lens': l['lens'], 'glow': l['glow'], 'group': l['group'],
                                 'spot': l['unityLight'] == 'Spot', 'angle': float(l.get('spotAngle', 0.0)),
                                 'pos': l['positionUnity'], 'dir': l['forwardUnity'], 'up': l['upUnity'], 'color': l['colorLinear'],
                                 'intensity': l['intensityURP'], 'range': l['range']})
    items.append(it)
os.makedirs(os.path.join(DST, 'Textures'), exist_ok=True)
for t in TEXTURES:
    shutil.copyfile(os.path.join(PKG, 'tex', t), os.path.join(DST, 'Textures', t))
data = {'version': c['meta']['version'], 'note': 'generated by tools/forest_airfield/make_unity_data.py from source/assets/forest_airfield; '
                                                 'read by StartPropsBuilder (Build Airfield Props)', 'items': items}
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    json.dump(data, f, ensure_ascii=False, indent=1)
print(OUT, {it['name']: (len(it['colliders']), len(it['lights']), len(it['sockets'])) for it in items})
