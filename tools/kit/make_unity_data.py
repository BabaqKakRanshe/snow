"""snow_kit 1.1 / KPP 2.1 / main 1.2 contracts -> JSON that Unity's JsonUtility reads (arrays, no keyed maps).

python -I tools/kit/make_unity_data.py <snow repo root>
  Snow/Assets/Kit/Data/Kit_Unity.json                    items (fbx, parts, sockets, colliders, power swaps, lights, glows)
  Snow/Assets/Locations/Forest/Data/Forest_KitInstances.json   the kit instances of Checkpoint, Barrier, Gate (kpp_contract)
                                                               and of R_Leitstand (main_contract)
Axes: positions, boxes and directions are the contracts' *Unity values. Hinge axes are negated (the contracts give the
axis as a position, M b, with "angle -> -angle"; SkyIslandInteractable turns by +angle, so its axis is -M b). Slides
and spins keep M b.
"""
import json, os, sys

root = sys.argv[1]
A = os.path.join(root, 'source/assets')


def load(p):
    with open(p, encoding='utf-8') as f:
        return json.load(f)


kit = load(os.path.join(A, 'snow_kit/snow_kit_contract.json'))
klights = load(os.path.join(A, 'snow_kit/snow_kit_lights.json'))
parts, sockets = kit['parts'], kit['sockets']

# halo sizes are not in the contract: TEMPORARY, by eye from the renders (beacon dome 0.14 m, flood head 0.32, street 0.5)
GLOW_SIZE = {'Glow_Beacon': 0.45, 'Glow_Flood': 1.1, 'Glow_Street': 1.3}

items = []
for name, it in kit['items'].items():
    ps = []
    for pn in it['parts']:
        p = parts[pn]
        kind = p['kind']
        if not (pn.startswith('IX_') or kind == 'spin' or pn.startswith('Glow_')):
            continue
        ax = p.get('axisUnity') or [0.0, 1.0, 0.0]
        if kind == 'hinge':
            ax = [-a for a in ax]
        rng = p.get('range') or [0, 0]
        ps.append({'name': pn, 'kind': kind, 'axis': ax, 'min': float(rng[0]), 'max': float(rng[1]),
                   'rest': float(p.get('rest') or 0.0), 'pivot': p['pivotUnity'], 'parent': p['parent'],
                   'glowSize': GLOW_SIZE.get(pn, 0.0)})
    socks = []
    for sn in it['sockets']:
        s = sockets[sn]
        socks.append({'name': sn, 'kind': s['kind'], 'parent': s['parent'], 'pos': s['posUnity'],
                      'dir': s.get('dirUnity') or s.get('forwardUnity') or [0.0, 0.0, 0.0], 'up': s.get('upUnity') or [0.0, 0.0, 0.0]})
    cols = [{'name': c['name'], 'parent': c['parent'], 'center': c['centerUnity'], 'size': c['sizeUnity']}
            for c in kit['colliders'] if c['item'] == name]
    swaps = []
    for pn in it.get('power_parts', []):
        pw = parts[pn]['power']
        swaps.append({'part': pn, 'on': pw['on'], 'off': pw['off']})
    lights = []
    for l in klights['lights']:
        if l['item'] != name:
            continue
        lights.append({'name': l['socket'], 'parent': 'Lens_Beacon' if l['type'] == 'beacon' else name,
                       'spot': l['unityLight'] == 'Spot', 'angle': float(l.get('spotAngle', 0)), 'pos': l['positionUnity'],
                       'dir': l['forwardUnity'], 'up': l['upUnity'], 'color': l['colorLinear'], 'intensity': l['intensityURP'],
                       'range': l['range'], 'rpm': float(l.get('rotateRPM', 0)), 'glow': l['glow']})
    items.append({'name': name, 'fbx': it['unity_fbx'], 'materials': it['materials'], 'parts': ps, 'sockets': socks,
                  'colliders': cols, 'swaps': swaps, 'lights': lights})

out = {'_doc': 'Generated by tools/kit/make_unity_data.py from source/assets/snow_kit (snow_kit_contract.json 1.1, '
               'snow_kit_lights.json). Read by Tools / Snow / Kit / Build Kit (KitBuilder).',
       'version': kit['meta']['version'], 'items': items}
kd = os.path.join(root, 'Snow/Assets/Kit/Data')
os.makedirs(kd, exist_ok=True)
with open(os.path.join(kd, 'Kit_Unity.json'), 'w', encoding='utf-8', newline='\n') as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print('kit items', len(items), 'parts', sum(len(i['parts']) for i in items), 'sockets', sum(len(i['sockets']) for i in items),
      'colliders', sum(len(i['colliders']) for i in items), 'lights', sum(len(i['lights']) for i in items))

# ------------------------------------------------------------------ instances
inst = []
kpp = load(os.path.join(A, 'forest_kpp/kpp_contract.json'))
for n, k in kpp['kit_instances'].items():
    inst.append({'name': n, 'item': k['item'], 'parent': k['parent'], 'root': k['root'],
                 'ix': [{'part': p, 'id': i} for p, i in k['ix_ids'].items()], 'pos': k['posUnity'], 'rot': k['rotUnity_xyzw'],
                 'scale': k['scaleUnity'], 'lightMask': 0, 'game': k.get('pos_game', [0, 0, 0])})
main = load(os.path.join(A, 'forest_main/main_contract.json'))
for n, k in main['kit_instances'].items():
    inst.append({'name': n, 'item': k['item'], 'parent': k['parent'], 'root': 'BaseMain',
                 'ix': [{'part': p, 'id': i} for p, i in k['ix_ids'].items()], 'pos': k['posUnity'], 'rot': k['rotUnity_xyzw'],
                 'scale': k['scaleUnity'], 'lightMask': k.get('lightMask', 0), 'game': [0, 0, 0]})
cams = []
for sn, s in kpp['sockets'].items():
    if s.get('kind') == 'camera':
        cams.append({'name': sn, 'parent': s['parent'], 'monitor': s['monitor'], 'fov': s['fov'], 'game': s['pos_game']})
fo = {'_doc': 'Generated by tools/kit/make_unity_data.py from kpp_contract.json (KPP 2.1, kit_instances, CAM_ sockets) and '
              'main_contract.json (1.2, Leit_*). pos / rot / scale: Unity axes in the parent\'s frame. lightMask 0 = the '
              'rendering layers of the root\'s own renderers. Read by ForestKppStep.',
      'instances': inst, 'cameras': cams}
with open(os.path.join(root, 'Snow/Assets/Locations/Forest/Data/Forest_KitInstances.json'), 'w', encoding='utf-8', newline='\n') as f:
    json.dump(fo, f, ensure_ascii=False, indent=1)
print('instances', len(inst), 'cameras', [c['name'] for c in cams])
