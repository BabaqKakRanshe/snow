"""forest_start 1.0 contract -> Snow/Assets/Locations/Forest/Start/Start_Unity.json for StartPropsBuilder (Unity).

Reads source/assets/forest_start/start_contract.json and start_lights.json; everything is taken in the Unity frame of each
root (the contract's *Unity fields). Colliders keep their parent's name (the builder turns the root-frame centre into the
parent's local frame). The doors are static for now (no SkyIslandInteractable: the Forest integration is not rerun for
this pack): 'pose' gives the angle they stand at (Unity degrees about axisUnity at pivotUnity; the contract's angle is
negated, Unity is left-handed).

python tools/forest_start/make_unity_data.py
"""
import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PKG = os.path.join(ROOT, 'source', 'assets', 'forest_start')
OUT = os.path.join(ROOT, 'Snow', 'Assets', 'Locations', 'Forest', 'Start', 'Start_Unity.json')
NAMES = ['StartBooth', 'StartCar', 'StartLamp', 'StartTyres', 'StartTrash']
POSE = {'IX_Door': 80.0, 'IX_CarDoor': 0.0}          # contract degrees the door stands at (booth: open, players can step in)
LIGHT_INTENSITY = {'LIGHT_Booth': 3.0, 'LIGHT_Flood': 16.0}   # the dark night's exposure (yard lamps: 16 at 26 m)
LIGHT_RANGE = {'LIGHT_Booth': 9.0, 'LIGHT_Flood': 24.0}

c = json.load(open(os.path.join(PKG, 'start_contract.json'), encoding='utf-8'))
lights = json.load(open(os.path.join(PKG, 'start_lights.json'), encoding='utf-8'))['lights']
items = []
for n in NAMES:
    it = {'name': n, 'fbx': f'Assets/Locations/Forest/Start/Models/{n}.fbx', 'colliders': [], 'lights': [], 'sockets': [], 'doors': []}
    for col in c['colliders']:
        if col['root'] == n:
            it['colliders'].append({'name': col['name'], 'parent': col['parent'], 'center': col['centerUnity'], 'size': col['sizeUnity']})
    for sn, s in c['sockets'].items():
        if s['root'] == n:
            it['sockets'].append({'name': sn, 'kind': s['kind'], 'pos': s['posUnity']})
    for pn, p in c['parts'].items():
        if p['root'] == n and p['kind'] == 'hinge':
            it['doors'].append({'name': pn, 'pivot': p['pivotUnity'], 'axis': p['axisUnity'], 'min': float(p['range'][0]),
                                'max': float(p['range'][1]), 'pose': -POSE.get(pn, 0.0)})
    for l in lights:
        if l['root'] == n:
            it['lights'].append({'name': l['socket'], 'lens': l['lens'], 'glow': l['glow'], 'group': l['group'],
                                 'spot': l['unityLight'] == 'Spot', 'angle': float(l.get('spotAngle', 0.0)),
                                 'pos': l['positionUnity'], 'dir': l['forwardUnity'], 'up': l['upUnity'], 'color': l['colorLinear'],
                                 'intensity': LIGHT_INTENSITY.get(l['socket'], l['intensityURP']),
                                 'range': LIGHT_RANGE.get(l['socket'], l['range'])})
    items.append(it)
data = {'version': c['meta']['version'], 'note': 'generated by tools/forest_start/make_unity_data.py from source/assets/forest_start; read by StartPropsBuilder', 'items': items}
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    json.dump(data, f, ensure_ascii=False, indent=1)
print(OUT, {it['name']: (len(it['colliders']), len(it['lights']), len(it['sockets']), len(it['doors'])) for it in items})
